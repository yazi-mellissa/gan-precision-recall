"""Collect every evaluation in runs/ into results/all_results.csv and results/summary.md.

A result is any results*.json under runs/: results_plain.json (plain sampling, the platform's way),
results.json (older evaluations) and sweeps/<setting>/results.json (tried samplers).
Run from the repo root:  python analysis/collect_results.py
"""
import os
import re
import csv
import glob
import json
from collections import defaultdict

# Final recipe (kept): spectral-norm MLP D + BCE + two learning rates + EMA of G; we submit ema/G.pth.
# Training seeds 0, 1, 2 for each length.
FINAL_GROUPS = {
    "150 epochs": ["e10_bce_mlpsn_ema", "e12_bce_mlpsn_ema_seed1", "e12_bce_mlpsn_ema_seed2"],
    "300 epochs": ["e12_bce_mlpsn_ema_300ep_seed0", "e13_bce_mlpsn_ema_300ep_seed1", "e13_bce_mlpsn_ema_300ep_seed2"],
    "500 epochs": ["e14_bce_mlpsn_ema_500ep_seed0"],
    "1000 epochs": ["e15_bce_mlpsn_ema_1000ep_seed0"],
}
FINAL_RUNS = [run for runs in FINAL_GROUPS.values() for run in runs]

EXPERIMENTS = {
    "e1": "Starter GAN (Adam beta1 0.9)",
    "e2": "Adam beta1 0.5 (+ OBRS / truncation sweeps)",
    "e4": "PR-divergence from scratch, lambda screen",
    "e6": "PR-divergence fine-tune from E2",
    "e7": "PR-divergence fine-tune, ratio from the BCE D",
    "e8": "R1 penalty + two learning rates (base model of E9-E11)",
    "e9": "PR-divergence fine-tune from E8",
    "e10": "Discriminator screen (SN, hinge, conv) + EMA of G",
    "e11": "Batch size, LR decay, 2 D steps, hinge bets",
    "e12": "Seeds of the two E10 winners, 300 epochs, EMA 0.9999",
    "e13": "Final recipe, 300 epochs, seeds 1-2",
    "e14": "Final recipe, 500 epochs, EMA snapshots every 100 epochs",
    "e15": "Final recipe, 1000 epochs, EMA snapshots every 100 epochs",
    "raphael": "Raphael's models on our evaluator",
}

FIELDS = ["experiment", "run", "generator", "sampler", "sampling_seed", "kept", "fid", "precision", "recall",
          "density", "coverage", "low_conf_share", "file"]


def parse(path):
    """Split runs/<run>[/ema][/sweeps/<setting>_seed<k>]/results*.json into table columns."""
    parts = path.replace("\\", "/").split("/")
    run = parts[1]
    generator = parts[2] if parts[2].startswith("ema") else "raw"  # ema, or ema_ep<N> snapshots
    sampler, seed = "plain", 0
    if "sweeps" in parts:
        setting = parts[parts.index("sweeps") + 1]
        m = re.match(r"(.*)_seed(\d+)$", setting)
        sampler, seed = (m.group(1), int(m.group(2))) if m else (setting, 0)
        if sampler in ("trunc_soft_psi1.0", "obrs_K1.0_standard", "obrs_K1.0_refreshed"):
            sampler = "plain"  # psi = 1 and K = 1 are plain sampling
    experiment = run.split("_")[0]
    kept = "yes" if run in FINAL_RUNS and generator == "ema" and sampler == "plain" else "no"
    return experiment, run, generator, sampler, seed, kept


def load_rows(runs_dir="runs"):
    rows = []
    for path in sorted(glob.glob(os.path.join(runs_dir, "**", "results*.json"), recursive=True)):
        with open(path) as f:
            r = json.load(f)
        if r.get("fid") is None:
            continue
        experiment, run, generator, sampler, seed, kept = parse(path)
        rows.append({"experiment": experiment, "run": run, "generator": generator, "sampler": sampler,
                     "sampling_seed": seed, "kept": kept, "fid": r["fid"],
                     "precision": r.get("vgg_precision"), "recall": r.get("vgg_recall"),
                     "density": r.get("vgg_density"), "coverage": r.get("vgg_coverage"),
                     "low_conf_share": (r.get("cnn") or {}).get("low_conf_share"),
                     "file": path.replace("\\", "/")})
    return rows


def mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def fmt(x, nd=2):
    return "" if x is None else f"{x:.{nd}f}"


def summary(rows):
    """One line per (run, generator): plain sampling (mean over sampling seeds) and the best tried sampler."""
    groups = defaultdict(list)
    for r in rows:
        groups[(r["experiment"], r["run"], r["generator"])].append(r)

    def key(k):
        m = re.match(r"e(\d+)", k[0])
        return (int(m.group(1)) if m else 99, k[1], k[2])

    lines = ["# Results summary", "",
             "Generated by `analysis/collect_results.py` from every `results*.json` in `runs/`.",
             "Local evaluator: Inception FID on 10k samples (same scale as the platform), VGG16 k=5 precision / recall",
             "(not calibrated to the platform). Plain = z ~ N(0, I), averaged over sampling seeds when several exist.", ""]

    lines += ["## Kept: final recipe (spectral-norm MLP D + EMA of G), plain sampling", ""]
    for length, runs in FINAL_GROUPS.items():
        final = [r for r in rows if r["kept"] == "yes" and r["run"] in runs]
        if not final:
            continue
        lines += [f"**{length}**", "", "| Run | FID | Precision | Recall |", "| --- | --- | --- | --- |"]
        for r in sorted(final, key=lambda r: r["run"]):
            lines.append(f"| {r['run']}/ema | {fmt(r['fid'])} | {fmt(r['precision'], 3)} | {fmt(r['recall'], 3)} |")
        lines += ["", f"Mean over {len(final)} training seed(s): FID {fmt(mean([r['fid'] for r in final]))}, "
                      f"P {fmt(mean([r['precision'] for r in final]), 3)}, R {fmt(mean([r['recall'] for r in final]), 3)}", ""]

    lines += ["## All runs", "",
              "| Exp. | Run | G | Plain FID | P | R | Best tried sampler | Its FID |",
              "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    last_exp = None
    for k in sorted(groups, key=key):
        exp, run, gen = k
        rs = groups[k]
        if exp != last_exp:
            lines.append(f"| **{exp}** | *{EXPERIMENTS.get(exp, '')}* | | | | | | |")
            last_exp = exp
        plain = [r for r in rs if r["sampler"] == "plain"]
        by_sampler = defaultdict(list)
        for r in rs:
            if r["sampler"] != "plain":
                by_sampler[r["sampler"]].append(r["fid"])
        best = min(by_sampler.items(), key=lambda kv: mean(kv[1])) if by_sampler else None
        lines.append(f"| {exp} | {run} | {gen} | {fmt(mean([r['fid'] for r in plain]))} | "
                     f"{fmt(mean([r['precision'] for r in plain]), 3)} | {fmt(mean([r['recall'] for r in plain]), 3)} | "
                     f"{best[0] if best else ''} | {fmt(mean(best[1])) if best else ''} |")
    return "\n".join(lines) + "\n"


def main():
    rows = load_rows()
    os.makedirs("results", exist_ok=True)
    with open("results/all_results.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)
    with open("results/summary.md", "w", encoding="utf-8") as f:
        f.write(summary(rows))
    print(f"{len(rows)} evaluations -> results/all_results.csv, results/summary.md")


if __name__ == "__main__":
    main()
